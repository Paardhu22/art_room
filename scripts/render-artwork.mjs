import { createServer } from "node:http";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { chromium } from "playwright";
import { scenes } from "../artwork/catalog.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const requested = process.argv.slice(2),
  chosen = requested.length
    ? scenes.filter((s) => requested.includes(s.id))
    : scenes;
if (requested.some((id) => !scenes.some((s) => s.id === id)))
  throw new Error("Unknown scene. Choose an ID from artwork/catalog.js.");
const server = createServer(async (req, res) => {
  try {
    const pathname = decodeURIComponent(
      new URL(req.url, "http://localhost").pathname,
    );
    const file = path.resolve(root, `.${pathname}`);
    if (!file.startsWith(root) || pathname.includes(".."))
      throw new Error("Not found");
    res.setHeader(
      "Content-Type",
      file.endsWith(".js")
        ? "text/javascript; charset=utf-8"
        : file.endsWith(".html")
          ? "text/html; charset=utf-8"
          : file.endsWith(".svg")
            ? "image/svg+xml"
            : "application/octet-stream",
    );
    res.end(await readFile(file));
  } catch {
    res.statusCode = 404;
    res.end();
  }
});
await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
let browser;
try {
  browser = await chromium.launch({
    executablePath: process.env.CHROMIUM_PATH || undefined,
    headless: true,
    args: ["--no-sandbox"],
  });
  await mkdir(path.join(root, "assets/artworks"), { recursive: true });
  const page = await browser.newPage({
    viewport: { width: 1300, height: 1500 },
    deviceScaleFactor: 1,
  });
  for (const scene of chosen) {
    const errors = [];
    const onError = (error) => errors.push(error.message);
    page.on("pageerror", onError);
    console.log(`Drawing ${scene.id} from JavaScript…`);
    await page.goto(
      `http://127.0.0.1:${server.address().port}/artwork/studio.html?scene=${scene.id}&seed=${scene.seed}`,
      { waitUntil: "load" },
    );
    await page.waitForFunction(
      () => window.artworkRendered || window.artworkError,
      undefined,
      { timeout: 120000 },
    );
    const problem = await page.evaluate(() => window.artworkError);
    if (problem || errors.length)
      throw new Error(`${scene.id}: ${problem || errors.join("; ")}`);
    const images = await page.evaluate(() => {
      const source = document.querySelector("#artwork");
      return [480, 800, 1200].map((size) => {
        const out = document.createElement("canvas");
        out.width = out.height = size;
        out.getContext("2d").drawImage(source, 0, 0, size, size);
        return { size, data: out.toDataURL("image/webp", 0.94).split(",")[1] };
      });
    });
    for (const { size, data } of images) {
      const bytes = Buffer.from(data, "base64");
      await writeFile(
        path.join(root, `assets/artworks/${scene.id}-${size}.webp`),
        bytes,
      );
      console.log(`  ${size}px: ${Math.round(bytes.length / 1024)} KB`);
    }
    page.off("pageerror", onError);
  }
  const collection = scenes.map((scene) => ({
    id: scene.id,
    title: scene.title,
    category: "places",
    label: scene.location,
    medium: scene.medium,
    note: scene.note,
    description: scene.description,
    alt: scene.alt,
    palette: scene.palette,
    image: `assets/artworks/${scene.id}-800.webp`,
    original: `assets/artworks/${scene.id}-1200.webp`,
    srcset: [480, 800, 1200]
      .map((size) => `assets/artworks/${scene.id}-${size}.webp ${size}w`)
      .join(", "),
    sketch: `artwork/studio.html?scene=${scene.id}&seed=${scene.seed}`,
  }));
  await writeFile(
    path.join(root, "artwork/collection.js"),
    `// Generated by npm run render:artwork from artwork/catalog.js.\nwindow.ARTWORKS.unshift(...${JSON.stringify(collection, null, 2)});\n`,
  );
  console.log(
    `Rendered ${chosen.length} original scene(s). Gallery metadata updated.`,
  );
} finally {
  await browser?.close();
  await new Promise((resolve) => server.close(resolve));
}
